// Radix MenuItem clicks the item itself on a pointerup that had no pointerdown
// on it (the press, drag, release gesture). When WebKit loses the release of
// the right button that opened the menu, a left click on an item delivers only
// pointerup and the native click, so the action ran twice (DF-278). After such
// a pointerup the first click selects and any later click of the same event
// task is rejected before the consumer and Radix see it. Keep this guard when
// the component is re-added with shadcn; context-menu.dom.test.tsx covers it.
function useSingleSelectionClick({
  onPointerDown,
  onPointerUp,
  onClick,
}: Pick<
  React.ComponentProps<"div">,
  "onPointerDown" | "onPointerUp" | "onClick"
>): Pick<
  React.ComponentProps<"div">,
  "onPointerDown" | "onPointerUp" | "onClick"
> {
  const pointerDownRef = React.useRef(false)
  const gestureRef = React.useRef<{ clicked: boolean } | null>(null)

  return {
    onPointerDown: (event) => {
      onPointerDown?.(event)
      pointerDownRef.current = true
    },
    onPointerUp: (event) => {
      onPointerUp?.(event)
      if (!pointerDownRef.current) {
        const gesture = { clicked: false }
        gestureRef.current = gesture
        setTimeout(() => {
          if (gestureRef.current === gesture) gestureRef.current = null
        })
      }
      pointerDownRef.current = false
    },
    onClick: (event) => {
      const gesture = gestureRef.current
      if (gesture?.clicked) {
        event.preventDefault()
        return
      }
      if (gesture) gesture.clicked = true
      onClick?.(event)
    },
  }
}

function ContextMenuItem({
  className,
  inset,
  variant = "default",
  onPointerDown,
  onPointerUp,
  onClick,
  ...props
}: React.ComponentProps<typeof ContextMenuPrimitive.Item> & {
  inset?: boolean
  variant?: "default" | "destructive"
}) {
  const selectionClick = useSingleSelectionClick({
    onPointerDown,
    onPointerUp,
    onClick,
  })

  return (
    <ContextMenuPrimitive.Item
      data-slot="context-menu-item"
      data-inset={inset}
      data-variant={variant}
      {...selectionClick}
      className={cn(
        "group/context-menu-item relative flex cursor-default items-center gap-1.5 rounded-md px-1.5 py-1 text-sm outline-hidden select-none focus:bg-accent focus:text-accent-foreground data-inset:pl-7 data-[variant=destructive]:text-destructive data-[variant=destructive]:focus:bg-destructive/10 data-[variant=destructive]:focus:text-destructive dark:data-[variant=destructive]:focus:bg-destructive/20 data-disabled:pointer-events-none data-disabled:opacity-50 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4 focus:*:[svg]:text-accent-foreground data-[variant=destructive]:*:[svg]:text-destructive",
        className
      )}
      {...props}
    />
  )
}

